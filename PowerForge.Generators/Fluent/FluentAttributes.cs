namespace PowerForge.Generators.Fluent {
    /// <summary>
    /// The attributes a library uses to steer the generator. They are added to every consuming compilation as internal,
    /// embedded types, so libraries that see each other's internals never get two conflicting copies.
    /// </summary>
    internal static class FluentAttributes {
        internal const string Namespace = "PowerForge.Fluent";
        internal const string Fluent = Namespace + ".FluentAttribute";
        internal const string NoFluent = Namespace + ".NoFluentAttribute";
        internal const string Child = Namespace + ".ChildAttribute";
        internal const string Forward = Namespace + ".FluentForwardAttribute";

        internal const string Source = @"// <auto-generated/>
#nullable enable
namespace Microsoft.CodeAnalysis {
    [global::Microsoft.CodeAnalysis.Embedded]
    internal sealed partial class EmbeddedAttribute : global::System.Attribute {
    }
}

namespace PowerForge.Fluent {
    /// <summary>
    /// On a class, base class or interface: generates fluent methods for that type and every public concrete type in this
    /// assembly that derives from it, plus the public settings types reachable from their properties.
    /// On a property: names its fluent method. A delegate-valued property must name one, because a method named after
    /// the property would never be called.
    /// </summary>
    [global::Microsoft.CodeAnalysis.Embedded]
    [global::System.AttributeUsage(global::System.AttributeTargets.Class | global::System.AttributeTargets.Interface | global::System.AttributeTargets.Property, Inherited = false)]
    internal sealed class FluentAttribute : global::System.Attribute {
        public FluentAttribute() {
        }

        public FluentAttribute(string name) {
            Name = name;
        }

        public string? Name { get; }
    }

    /// <summary>Leaves a property, or a whole type, out of the generated methods.</summary>
    [global::Microsoft.CodeAnalysis.Embedded]
    [global::System.AttributeUsage(global::System.AttributeTargets.Class | global::System.AttributeTargets.Property, Inherited = false)]
    internal sealed class NoFluentAttribute : global::System.Attribute {
    }

    /// <summary>Names the methods that add one item to a collection property when the singular rule does not fit.</summary>
    [global::Microsoft.CodeAnalysis.Embedded]
    [global::System.AttributeUsage(global::System.AttributeTargets.Property, Inherited = false)]
    internal sealed class ChildAttribute : global::System.Attribute {
        public ChildAttribute(string name) {
            Name = name;
        }

        public string Name { get; }
    }

    /// <summary>
    /// Generates the method <c>name</c> on every fluent type deriving from the annotated type, once per public or internal
    /// static overload <c>method(owner, value)</c> of <c>type</c>. Used when a value must go through a helper rather
    /// than a property setter. A property with the same name gets no generated methods of its own.
    /// </summary>
    [global::Microsoft.CodeAnalysis.Embedded]
    [global::System.AttributeUsage(global::System.AttributeTargets.Class | global::System.AttributeTargets.Interface, AllowMultiple = true, Inherited = false)]
    internal sealed class FluentForwardAttribute : global::System.Attribute {
        public FluentForwardAttribute(string name, global::System.Type type, string method) {
            Name = name;
            Type = type;
            Method = method;
        }

        public string Name { get; }

        public global::System.Type Type { get; }

        public string Method { get; }

        /// <summary>The documentation summary of the generated methods.</summary>
        public string? Summary { get; set; }

        /// <summary>The documentation of the value parameter.</summary>
        public string? ValueSummary { get; set; }
    }
}
";
    }
}
