using System.Management.Automation.Language;
using System.Text;

namespace PowerForge;

/// <summary>
/// Generates a runtime-independent console entry point for an eligible top-level PowerShell script.
/// </summary>
internal static class PowerShellTypedExecutableEmitter
{
    private const string ProgramTemplate = "PowerForge.PowerShell.Compilation.TypedExecutableProgram.cs.template";

    internal static PowerShellTypedExecutableEmission Emit(string sourcePath, PowerShellCompilationPlan plan, string targetFramework)
    {
        if (plan.Files.Length != 1)
            throw new InvalidOperationException("A typed executable requires exactly one PowerShell source file.");
        var scriptUnits = plan.Files[0].Units.Where(static unit => unit.Kind == PowerShellCompilationUnitKind.Script).ToArray();
        var functionUnits = plan.Files[0].Units.Where(static unit => unit.Kind == PowerShellCompilationUnitKind.Function).ToArray();
        if (functionUnits.Length > 0)
            throw new InvalidOperationException("The first typed executable subset accepts top-level script code only; local PowerShell function declarations are not compiled into the entry point yet.");
        if (scriptUnits.Length != 1 || !scriptUnits[0].IsCompilable || !plan.CanProceed)
        {
            var firstBlocker = plan.Files
                .SelectMany(static file => file.Diagnostics.Concat(file.Units.SelectMany(static unit => unit.Diagnostics)))
                .FirstOrDefault();
            throw new InvalidOperationException(firstBlocker is null
                ? "Strict typed executable generation requires one fully eligible top-level script unit with no fallback diagnostics."
                : $"Strict typed executable generation requires one fully eligible top-level script unit. First blocker: {firstBlocker.Message}");
        }

        Token[] tokens;
        ParseError[] errors;
        var ast = Parser.ParseFile(sourcePath, out tokens, out errors);
        if (errors.Length > 0)
            throw new InvalidOperationException("Typed executable source could not be parsed.");
        var statements = ast.EndBlock?.Statements
            .Where(static statement => statement is not FunctionDefinitionAst)
            .ToArray() ?? Array.Empty<StatementAst>();
        var method = new PowerShellCSharpMethodEmitter(sourcePath, ast, "<script>", "Invoke", statements, targetFramework).Emit();
        PowerShellTypedExecutableOutputPolicy.EnsureSupported(method.ReturnType);
        var compiledSource = new StringBuilder()
            .AppendLine("// <auto-generated />")
            .AppendLine("#nullable enable")
            .AppendLine()
            .AppendLine("namespace PowerForge.Compiled;")
            .AppendLine()
            .AppendLine("public static class CompiledPowerShellScript")
            .AppendLine("{")
            .AppendLine(method.Source)
            .AppendLine("}")
            .ToString();

        var parameters = ast.ParamBlock?.Parameters.ToArray() ?? Array.Empty<ParameterAst>();
        var parameterSpecs = string.Join(Environment.NewLine, parameters.Select(parameter =>
            "        new ParameterSpec(" + PowerShellCSharpLiteral.QuoteString(parameter.Name.VariablePath.UserPath) + ", typeof(" +
            PowerShellCSharpMethodEmitter.GetTypeName(parameter.StaticType) + "), " +
            (IsMandatory(parameter) ? "true" : "false") + "),"));
        var arguments = string.Join(", ", parameters.Select(parameter =>
            "(" + PowerShellCSharpMethodEmitter.GetTypeName(parameter.StaticType) + ")values[" +
            PowerShellCSharpLiteral.QuoteString(parameter.Name.VariablePath.UserPath) + "]"));
        var invocation = "CompiledPowerShellScript." + method.GeneratedName + "(" + arguments + ")";
        var invocationSource = method.ReturnType == typeof(void)
            ? "            " + invocation + ";" + Environment.NewLine + "            return 0;"
            : "            var result = " + invocation + ";" + Environment.NewLine +
              "            WriteResult(result);" + Environment.NewLine + "            return 0;";
        var programSource = ReadTemplate(ProgramTemplate)
            .Replace("{{PARAMETER_SPECS}}", parameterSpecs)
            .Replace("{{INVOCATION}}", invocationSource);
        return new PowerShellTypedExecutableEmission(compiledSource, programSource);
    }

    private static bool IsMandatory(ParameterAst parameter)
    {
        foreach (var attribute in parameter.Attributes.OfType<AttributeAst>())
        {
            if (!attribute.TypeName.Name.Equals("Parameter", StringComparison.OrdinalIgnoreCase) &&
                !attribute.TypeName.Name.Equals("ParameterAttribute", StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            foreach (var argument in attribute.NamedArguments)
            {
                if (!argument.ArgumentName.Equals("Mandatory", StringComparison.OrdinalIgnoreCase))
                    continue;
                if (argument.ExpressionOmitted)
                    return true;
                if (argument.Argument is ConstantExpressionAst { Value: bool constant })
                    return constant;
                if (argument.Argument is VariableExpressionAst variable)
                    return variable.VariablePath.UserPath.Equals("true", StringComparison.OrdinalIgnoreCase);
            }
        }
        return false;
    }

    private static string ReadTemplate(string resourceName)
    {
        using var stream = typeof(PowerShellTypedExecutableEmitter).Assembly.GetManifestResourceStream(resourceName)
            ?? throw new InvalidOperationException($"Embedded compilation template '{resourceName}' was not found.");
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }
}

internal sealed class PowerShellTypedExecutableEmission
{
    internal PowerShellTypedExecutableEmission(string compiledSource, string programSource)
    {
        CompiledSource = compiledSource;
        ProgramSource = programSource;
    }

    internal string CompiledSource { get; }
    internal string ProgramSource { get; }
}
